export interface RenderInput {
  doc: PrescriptionDoc;
  patient: PatientInfo;
  doctor: DoctorHeader;
  chamber: ChamberHeader;
  /** All active chambers of the doctor, for `chambersInHeader`. */
  chambers?: ChamberHeader[];
  date: string; // ISO yyyy-mm-dd
  settings: PrintSettings;
  /** Pre-rendered QR code SVG markup (generated by the caller). */
  qrSvg?: string;
  /** Signature image data URL. */
  signatureDataUrl?: string;
  /** Font sources for @font-face; data: URLs or absolute URLs. */
  fonts: { bengali: string; latin: string };
  /** Printed at the bottom (e.g. verification URL text). */
  footerNote?: string;
}

const esc = (s: string | undefined | null): string =>
  (s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

export function paperDimensions(paper: PaperSize): { widthMm: number; heightMm: number } {
  if (typeof paper === "object") return paper;
  return { A4: { widthMm: 210, heightMm: 297 }, A5: { widthMm: 148, heightMm: 210 }, Letter: { widthMm: 216, heightMm: 279 } }[
    paper
  ];
}

function drugName(item: RxItem, s: PrintSettings): string {
  const brand = s.drugNameCase === "upper" ? item.brandName.toUpperCase() : item.brandName;
  const generic = item.genericName ?? "";
  const strength = item.strength ? ` ${item.strength}` : "";
  const form = item.form ? `${item.form} ` : "";
  if (s.genericDisplay === "generic" && generic) {
    return `${esc(form)}<b>${esc(s.drugNameCase === "upper" ? generic.toUpperCase() : generic)}</b>${esc(strength)}`;
  }
  const gen = s.genericDisplay === "brand_generic" && generic ? ` <span class="gen">(${esc(generic)})</span>` : "";
  return `${esc(form)}<b>${esc(brand)}</b>${esc(strength)}${gen}`;
}

function ageText(p: PatientInfo, n: Numerals): string {
  const parts: string[] = [];
  if (p.ageYears) parts.push(`${digits(p.ageYears, n)} Y`);
  if (p.ageMonths) parts.push(`${digits(p.ageMonths, n)} M`);
  if (p.ageDays) parts.push(`${digits(p.ageDays, n)} D`);
  return parts.join(" ");
}

function section(title: string, body: string): string {
  return body ? `<section><h3>${esc(title)}</h3>${body}</section>` : "";
}

function list(items: string[]): string {
  const clean = items.map((s) => s.trim()).filter(Boolean);
  return clean.length ? `<ul>${clean.map((i) => `<li>${esc(i)}</li>`).join("")}</ul>` : "";
}

function oeBlock(doc: PrescriptionDoc): string {
  const v = doc.vitals;
  const rows: string[] = [];
  if (v.bpSystolic && v.bpDiastolic) rows.push(`BP: ${v.bpSystolic}/${v.bpDiastolic} mmHg`);
  if (v.pulse) rows.push(`Pulse: ${v.pulse} b/m`);
  if (v.tempF) rows.push(`Temp: ${v.tempF} °F`);
  if (v.spo2) rows.push(`SpO₂: ${v.spo2}%`);
  if (v.respRate) rows.push(`RR: ${v.respRate}/min`);
  if (v.weightKg) rows.push(`Wt: ${v.weightKg} kg`);
  if (v.heightCm) rows.push(`Ht: ${v.heightCm} cm`);
  const b = bmi(v.weightKg, v.heightCm);
  if (b) rows.push(`BMI: ${b}`);
  const kv = (doc.oeFindings ?? []).filter((l) => l.label.trim() && l.value.trim());
  const findings = kv.length
    ? `<table class="kv">${kv.map((l) => `<tr><td class="k">${esc(l.label)}</td><td>: ${esc(l.value)}</td></tr>`).join("")}</table>`
    : "";
  const exam = doc.examination ? `<p class="pre">${esc(doc.examination)}</p>` : "";
  return list(rows) + findings + exam;
}

/** "১ মাস পর আসবেন। (তারিখঃ ১১-০৭-২০২৬)": the relative period plus the date it falls on. */
function followUpText(doc: PrescriptionDoc, date: string, s: PrintSettings): string {
  const f = doc.followUp;
  const due = followUpDate(f, date);
  if (!f || f.kind === "none" || !due) return "";
  const when = formatDateDmy(due, s.numerals);
  if (f.kind === "date") return s.instructionLang === "bn" ? `${when} তারিখে আসবেন।` : `Come on ${when}.`;
  const d = formatDuration({ kind: "fixed", value: f.value, unit: f.unit }, s.instructionLang, s.numerals);
  return s.instructionLang === "bn" ? `${d} পর আসবেন। (তারিখঃ ${when})` : `Come after ${d} (on ${when}).`;
}

/** "Birth wt: 1.7 kg", "Born at 30 weeks" for children under 2. */
function birthNotes(p: PatientInfo): string[] {
  if (p.ageYears && p.ageYears >= 2) return [];
  return [
    p.birthWeightKg ? `Birth wt: ${p.birthWeightKg} kg` : "",
    p.gestationalAgeWeeks ? `Born at ${p.gestationalAgeWeeks} weeks${p.gestationalAgeWeeks < 37 ? " (preterm)" : ""}` : "",
  ].filter(Boolean);
}

/** Name, address, schedule (or free-text hours) and phones of one chamber. */
function chamberBlock(c: ChamberHeader, lang: Lang, n: Numerals): string {
  if (!c.name && !c.address) return "";
  const slots = (c.schedule ?? []).map((sl) => formatSlot(sl, lang, n)).filter(Boolean);
  const lines = [
    c.address,
    ...(slots.length ? slots : c.hours ? [c.hours] : []),
    c.serialPhone ? `${lang === "bn" ? "সিরিয়াল" : "Serial"}: ${c.serialPhone}` : "",
    c.phone ?? "",
  ].filter(Boolean);
  return `<div class="chamber"><b>${esc(c.name)}</b>${lines.map((l) => `<br>${esc(l)}`).join("")}</div>`;
}

/** Bangla rendering of a BMDC number: "A-39542" → "এ-৩৯৫৪২". */
function bmdcBn(n: string): string {
  return toBnDigits(n.replace(/^A(?=[-\s\d])/i, "এ").replace(/^D(?=[-\s\d])/i, "ডি"));
}

const COURSE_LINE = { bn: "সম্পূর্ণ কোর্স শেষ করুন", en: "Complete the full course" };

/** Render a self-contained, printable HTML document for a prescription. */
export function renderPrescriptionHtml(input: RenderInput): string {
  const { doc, patient, doctor, chamber, settings: s } = input;
  const { widthMm, heightMm } = paperDimensions(s.paper);
  const pad = s.mode === "pad";
  const lang = s.instructionLang;
  const hidden = new Set(s.hiddenSections ?? []);
  const sec = (key: SectionKey, body: string) =>
    hidden.has(key) ? "" : section(s.sectionLabels?.[key]?.trim() || defaultSectionLabel(key, lang), body);

  const logo = safeImageDataUrl(chamber.logoDataUrl);
  const header = pad
    ? ""
    : `<header>
        <div class="doc">
          <div class="dname">${esc(doctor.nameEn)}</div>
          <div>${esc(doctor.degreesEn.join(", "))}</div>
          ${doctor.designation ? `<div>${esc(doctor.designation)}</div>` : ""}
          ${doctor.institution ? `<div>${esc(doctor.institution)}</div>` : ""}
          <div class="bmdc">BMDC Reg. No: ${esc(doctor.bmdcNumber)}</div>
        </div>
        ${logo ? `<div class="logo"><img src="${esc(logo)}" alt=""></div>` : ""}
        ${
          doctor.nameBn
            ? `<div class="doc bn-right">
                <div class="dname">${esc(doctor.nameBn)}</div>
                <div>${esc((doctor.degreesBn ?? []).join(", "))}</div>
                ${doctor.specialty ? `<div>${esc(doctor.specialty)}</div>` : ""}
                ${doctor.bmdcNumber ? `<div class="bmdc-bn">বিএমডিসি রেজি. নং: ${esc(bmdcBn(doctor.bmdcNumber))}</div>` : ""}
              </div>`
            : ""
        }
      </header>${
        s.chambersInHeader && input.chambers?.length
          ? `<div class="chambers">${input.chambers.map((c) => chamberBlock(c, lang, s.numerals)).join("")}</div>`
          : ""
      }`;

  const patientStrip = `<div class="patient">
      <span><b>Name:</b> ${esc(patient.name)}</span>
      <span><b>Age:</b> ${esc(ageText(patient, "en"))}</span>
      <span><b>Sex:</b> ${esc(patient.sex ? patient.sex[0]!.toUpperCase() : "")}</span>
      ${patient.address ? `<span><b>Address:</b> ${esc(patient.address)}</span>` : ""}
      <span><b>Date:</b> ${esc(formatDateDmy(input.date, "en", "/"))}</span>
      ${patient.patientCode ? `<span><b>ID:</b> ${esc(patient.patientCode)}</span>` : ""}
      ${doc.referredBy?.trim() ? `<span><b>Ref By:</b> ${esc(doc.referredBy)}</span>` : ""}
    </div>`;

  // Older prescriptions have no `kind`; their drums are titled "Right TM" / "Left TM".
  const hasTm = (doc.diagrams ?? []).some((d) => d.kind === "tm" || /^(Right|Left) TM$/.test(d.title));
  const blankTm = s.tmMapAlways && !hasTm
    ? [{ title: "Right TM", svg: eardrumSvg(undefined, "right"), kind: "tm" as const, section: "ear" }, { title: "Left TM", svg: eardrumSvg(undefined, "left"), kind: "tm" as const, section: "ear" }]
    : [];
  const blankSketches = (Array.isArray(s.sketchesAlways) ? s.sketchesAlways : [])
    .filter((id) => isSketchId(id) && !(doc.diagrams ?? []).some((d) => d.kind === "sketch" && d.ref === id))
    .map((id) => ({ title: SKETCHES[id].title, svg: sketchSvg(id), kind: "sketch" as const, ref: id, section: SKETCHES[id].section }));
  const allDiagrams = [...blankTm, ...(doc.diagrams ?? []), ...blankSketches];
  const figures = (ds: typeof allDiagrams) =>
    ds
      // Diagrams come from the client-writable prescription doc: sanitise before embedding.
      .map((d) => `<figure class="diagram${d.kind === "tm-legend" || d.kind === "legend" ? " legend" : ""}${d.kind === "sketch" && d.ref === "neck" ? " neck" : ""}"><div class="svg">${sanitizeSvg(d.svg)}</div><figcaption>${esc(d.title)}</figcaption></figure>`)
      .join("");

  // Each picture prints under its own exam section; the rest (older prescriptions, or a blank
  // "always print" picture whose section has no findings) print together after all findings.
  const groups = doc.specialtyFindings ?? [];
  const placed = (d: (typeof allDiagrams)[number]) => typeof d.section === "string" && groups.some((g) => g.id === d.section);
  const specialty = groups
    .map((g) => {
      const lines = g.lines.length ? `<ul>${g.lines.map((l) => `<li><b>${esc(l.label)}:</b> ${esc(l.value)}</li>`).join("")}</ul>` : "";
      const pics = g.id ? figures(allDiagrams.filter((d) => d.section === g.id)) : "";
      return section(g.title, lines + (pics ? `<div class="diagrams">${pics}</div>` : ""));
    })
    .join("");
  const diagrams = figures(allDiagrams.filter((d) => !placed(d)));

  const barcodeSvg = s.showBarcode && patient.patientCode ? code39Svg(patient.patientCode) : null;
  const left = [
    barcodeSvg ? `<div class="barcode">${barcodeSvg}<div>*${esc(patient.patientCode!.toUpperCase())}*</div></div>` : "",
    doc.visitNo ? `<div class="visit-no">Visit No: ${doc.visitNo}</div>` : "",
    sec("cc", list(doc.chiefComplaints)),
    sec("history", doc.history ? `<p class="pre">${esc(doc.history)}</p>` : ""),
    sec("oe", oeBlock(doc)),
    specialty,
    diagrams ? `<section class="diagrams">${diagrams}</section>` : "",
    sec("ix", list(doc.investigations)),
    sec("dx", list(doc.diagnoses)),
    sec("plan", list(doc.plan ?? [])),
    sec("notes", list([...birthNotes(patient), ...(doc.notes ?? [])])),
  ].join("");

  const items = doc.items
    .map((it, i) => {
      const { main, duration } = formatInstructionParts(it, lang, s.numerals);
      return `<li class="rx-item">
        <div class="lines">
          <div class="drug"><span class="num">${digits(i + 1, s.numerals)}.</span> ${drugName(it, s)}</div>
          ${main ? `<div class="instr">${esc(main)}</div>` : ""}
          ${it.note ? `<div class="note">${esc(it.note)}</div>` : ""}
          ${it.isAntibiotic ? `<div class="note course">${COURSE_LINE[lang]}</div>` : ""}
        </div>
        <div class="dur">${duration ? `- ${esc(duration)}` : ""}</div>
      </li>`;
    })
    .join("");

  const fu = followUpText(doc, input.date, s);
  const right = [
    `<div class="rx-symbol">℞</div>`,
    items ? `<ol class="rx">${items}</ol>` : "",
    doc.rxNote?.trim() ? `<div class="rx-note pre">${esc(doc.rxNote.trim())}</div>` : "",
    sec("advice", list(doc.advice)),
    fu ? sec("followUp", `<p>${esc(fu)}</p>`) : "",
  ].join("");

  const footerText = chamber.footerText?.trim();
  const footerChamber = s.chambersInHeader && input.chambers?.length ? "" : chamberBlock(chamber, lang, s.numerals);
  const footer =
    pad || (!footerChamber && !footerText)
      ? ""
      : `<footer>${footerChamber}${footerText ? `<div class="policy">${esc(footerText)}</div>` : ""}</footer>`;

  const sig = safeImageDataUrl(input.signatureDataUrl);
  const signature = `<div class="sign">${
    sig ? `<img src="${esc(sig)}" alt="">` : ""
  }<div class="line">Signature</div></div>`;

  const qr = s.showQr && input.qrSvg ? `<div class="qr">${sanitizeSvg(input.qrSvg)}</div>` : "";

  const m = pageMargins(s);
  const contentHeightMm = heightMm - m.top - m.bottom;

  return `<!doctype html>
<html lang="bn">
<head>
<meta charset="utf-8">
<title>Prescription — ${esc(patient.name)}</title>
<style>
@font-face { font-family: "RxBengali"; src: url("${input.fonts.bengali}") format("truetype"); font-weight: 100 900; }
@font-face { font-family: "RxLatin"; src: url("${input.fonts.latin}") format("truetype"); font-weight: 100 900; }
/* Page margins carry the pad's pre-printed header/footer space and the printer offset,
   so they repeat on every page when a long prescription flows onto page 2. */
@page { size: ${widthMm}mm ${heightMm}mm; margin: ${m.top}mm ${m.right}mm ${m.bottom}mm ${m.left}mm; }
* { box-sizing: border-box; }
html, body { margin: 0; padding: 0; background: #fff; color: #000; }
body { font-family: "RxLatin", "RxBengali", sans-serif; font-size: ${s.fontSizePt}pt; line-height: 1.35; }
.page { min-height: ${contentHeightMm}mm; display: flex; flex-direction: column; }
header { display: flex; justify-content: space-between; border-bottom: 1.5pt solid #000; padding-bottom: 2mm; }
header .dname { font-size: 1.35em; font-weight: 700; }
header .bn-right { text-align: right; }
header .bmdc, header .bmdc-bn { font-weight: 600; }
.patient { display: flex; flex-wrap: wrap; gap: 1mm 6mm; padding: 2mm 0; border-bottom: 0.75pt solid #000; }
.body { flex: 1; display: grid; grid-template-columns: ${s.leftColumnPct}% 1fr; }
.left { border-right: 0.75pt solid #000; padding: 2mm 3mm 2mm 0; }
.right { padding: 2mm 0 2mm 4mm; }
section { margin-bottom: 2.5mm; break-inside: avoid; }
h3 { font-size: 0.95em; margin: 0 0 1mm; text-decoration: underline; }
ul { margin: 0; padding-left: 4mm; }
.pre { white-space: pre-wrap; margin: 0; }
.rx-symbol { font-size: 2em; font-weight: 700; line-height: 1; margin-bottom: 1mm; }
ol.rx { list-style: none; padding: 0; margin: 0 0 3mm; }
.rx-item { margin-bottom: 2.5mm; break-inside: avoid; display: grid; grid-template-columns: 1fr auto; column-gap: 4mm; }
.rx-item .dur { align-self: center; white-space: nowrap; }
.visit-no { font-weight: 700; margin-bottom: 2mm; }
.kv { border-collapse: collapse; }
.kv td { padding: 0 1mm 0 0; vertical-align: top; }
.kv .k { font-weight: 600; white-space: nowrap; }
.rx-note { margin: 0 0 3mm; }
.rx-item .num { display: inline-block; min-width: 5mm; }
.rx-item .gen { font-size: 0.85em; }
.rx-item .instr, .rx-item .note { padding-left: 5mm; }
.rx-item .note { font-size: 0.9em; }
ul + .diagrams { margin-top: 1.5mm; }
.diagram { display: inline-block; margin: 0 2mm 2mm 0; text-align: center; font-size: 0.8em; }
.diagram .svg svg { width: 28mm; height: auto; }
.diagram.legend { vertical-align: top; text-align: left; }
.diagram.legend .svg svg { width: 32mm; }
.diagram.neck .svg svg { width: 30mm; }
.bottom { display: flex; justify-content: space-between; align-items: flex-end; padding-top: 2mm; break-inside: avoid; }
.qr svg { width: 18mm; height: 18mm; }
.sign { text-align: center; min-width: 45mm; margin-left: auto; }
.sign img { max-height: 14mm; max-width: 45mm; }
.sign .line { border-top: 0.75pt solid #000; padding-top: 1mm; }
footer { border-top: 1.5pt solid #000; padding-top: 2mm; font-size: 0.9em; break-inside: avoid; }
footer .policy { text-align: center; margin-top: 1mm; }
header .logo { display: flex; align-items: center; }
header .logo img { max-height: 18mm; max-width: 30mm; }
.chambers { display: grid; grid-template-columns: repeat(auto-fit, minmax(50mm, 1fr)); gap: 2mm 4mm; padding: 1.5mm 0; border-bottom: 0.75pt solid #000; font-size: 0.85em; }
.barcode { margin-bottom: 2mm; text-align: center; font-size: 0.8em; letter-spacing: 0.5pt; }
.barcode svg { display: block; margin: 0 auto 0.5mm; }
.footnote { font-size: 0.75em; text-align: center; color: #333; }
@media screen {
  body { background: #e5e7eb; }
  .sheet { width: ${widthMm}mm; min-height: ${heightMm}mm; margin: 8mm auto; background: #fff; box-shadow: 0 1px 6px rgba(0,0,0,.2);
    padding: ${m.top}mm ${m.right}mm ${m.bottom}mm ${m.left}mm; }
}
</style>
</head>
<body>
<div class="sheet">
<div class="page">
  ${header}
  ${patientStrip}
  <div class="body">
    <div class="left">${left}</div>
    <div class="right">${right}</div>
  </div>
  <div class="bottom">${qr}${signature}</div>
  ${input.footerNote ? `<div class="footnote">${esc(input.footerNote)}</div>` : ""}
  ${footer}
</div>
</div>
</body>
</html>`;
}

/** Effective @page margins: user margins + pad reserved space + printer offset (never negative). */
export function pageMargins(s: PrintSettings): { top: number; right: number; bottom: number; left: number } {
  const pad = s.mode === "pad";
  const clamp = (n: number) => Math.max(0, Math.round(n * 10) / 10);
  return {
    top: clamp(s.marginTopMm + (pad ? s.padHeaderMm : 0) + s.offsetYmm),
    bottom: clamp(s.marginBottomMm + (pad ? s.padFooterMm : 0) - s.offsetYmm),
    left: clamp(s.marginLeftMm + s.offsetXmm),
    right: clamp(s.marginRightMm - s.offsetXmm),
  };
}
