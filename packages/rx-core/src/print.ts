export type PaperSize = "A4" | "A5" | "Letter" | { widthMm: number; heightMm: number };

export interface PrintSettings {
  paper: PaperSize;
  /** `letterhead` prints the full header/footer; `pad` prints only the body onto a pre-printed pad. */
  mode: "letterhead" | "pad";
  /** Printer alignment correction, applied to everything. */
  offsetXmm: number;
  offsetYmm: number;
  marginTopMm: number;
  marginRightMm: number;
  marginBottomMm: number;
  marginLeftMm: number;
  /** In pad mode: blank space reserved for the pre-printed header/footer. */
  padHeaderMm: number;
  padFooterMm: number;
  fontSizePt: number;
  leftColumnPct: number;
  drugNameCase: "upper" | "as_is";
  genericDisplay: "brand" | "brand_generic" | "generic";
  instructionLang: Lang;
  numerals: Numerals;
  showQr: boolean;
  /** Chamber details printed with the visiting information (footer right, or the header chamber list). */
  showSchedule: boolean;
  showSerialPhone: boolean;
  showChamberPhone: boolean;
  /** Custom section headings, e.g. `{ dx: "Δ", ix: "Investigations" }`; missing keys use the defaults. */
  sectionLabels: Partial<Record<SectionKey, string>>;
  /** Sections that are recorded but not printed. */
  hiddenSections: SectionKey[];
  /** Print the patient ID as a Code 39 barcode at the top of the clinical column. */
  showBarcode: boolean;
  /** Letterhead: list all of the doctor's chambers under the header instead of the current one in the footer. */
  chambersInHeader: boolean;
  /** ENT: print blank right/left eardrums when nothing was marked, for marking by pen. */
  tmMapAlways: boolean;
  /** ENT: throat/neck pictures printed blank when nothing was marked. */
  sketchesAlways: SketchId[];
}

/** Printable sections whose heading can be renamed or hidden. */
export type SectionKey = "cc" | "history" | "oe" | "labs" | "ix" | "dx" | "plan" | "notes" | "advice" | "followUp";

export const SECTION_KEYS: SectionKey[] = ["cc", "history", "oe", "labs", "ix", "dx", "plan", "notes", "advice", "followUp"];

/** Default headings. Clinical headings stay English (as on Bangladeshi pads); advice and follow-up follow the language. */
export function defaultSectionLabel(key: SectionKey, lang: Lang): string {
  if (key === "advice") return lang === "bn" ? "উপদেশ" : "Advice";
  if (key === "followUp") return lang === "bn" ? "পুনরায় সাক্ষাৎ" : "Follow-up";
  return { cc: "C/C", history: "History", oe: "O/E", labs: "Reports", ix: "Ix", dx: "Dx", plan: "Plan", notes: "Note" }[key];
}

