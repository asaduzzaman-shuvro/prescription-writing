export interface RenderInput {
  doc: PrescriptionDoc;
  patient: PatientInfo;
  doctor: DoctorHeader;
  chamber: ChamberHeader;
  /** All active chambers of the doctor, for `chambersInHeader`. */
  chambers?: ChamberHeader[];
  date: string; // ISO yyyy-mm-dd
  settings: PrintSettings;
  /** Pre-rendered QR code SVG markup (generated by the caller). */
  qrSvg?: string;
  /** Signature image data URL. */
  signatureDataUrl?: string;
  /** Font sources for @font-face; data: URLs or absolute URLs. */
  fonts: { bengali: string; latin: string };
  /** Printed at the bottom (e.g. verification URL text). */
  footerNote?: string;
  /**
   * Pages the prescription takes, measured from a first render (`printPagesFor` in the browser, the PDF's page count
   * on the server). 2+ numbers the pages and pins the footer to the bottom of the last one.
   */
  pages?: number;
}

/** Bottom page margin the "Page 1 of 2" number prints in, when there are 2+ pages. */
const PAGE_NO_MM = 7;

/** Height of the content area on each page, in mm: the paper less the margins (and the page-number strip if numbered). */
export function pageContentHeightMm(s: PrintSettings, numbered: boolean): number {
  const m = pageMargins(s);
  return paperDimensions(s.paper).heightMm - m.top - (numbered ? Math.max(m.bottom, PAGE_NO_MM) : m.bottom);
}

/** How many pages a prescription takes, from the height (mm) its page box lays out at with no minimum height. */
export function printPagesFor(contentHeightMm: number, s: PrintSettings): number {
  if (!(contentHeightMm > pageContentHeightMm(s, false) + 0.5)) return 1;
  return Math.min(50, Math.ceil((contentHeightMm - 0.5) / pageContentHeightMm(s, true)));
}

/** Saved PDF name: name, mobile, patient id and visit date, so one patient's prescriptions stay distinct. */
export function prescriptionFileName(input: {
  name: string;
  mobile?: string | null;
  id?: string | null;
  date?: string | null;
}): string {
  const stem = [input.name, input.mobile, input.id, input.date].filter((part) => part && part.trim()).join(" ");
  const cleaned = stem.replace(/[\\/:*?"<>|]+/g, " ").replace(/\s+/g, " ").trim();
  return `${(cleaned || "prescription").slice(0, 140)}.pdf`;
}

/** Text for HTML (element content or a quoted attribute). */
export const escapeHtml = (s: string | undefined | null): string =>
  (s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
const esc = escapeHtml;

export function paperDimensions(paper: PaperSize): { widthMm: number; heightMm: number } {
  if (typeof paper === "object") return paper;
  return { A4: { widthMm: 210, heightMm: 297 }, A5: { widthMm: 148, heightMm: 210 }, Letter: { widthMm: 216, heightMm: 279 } }[
    paper
  ];
}

function drugName(item: RxItem, s: PrintSettings): string {
  const brand = s.drugNameCase === "upper" ? item.brandName.toUpperCase() : item.brandName;
  const generic = item.genericName ?? "";
  const strength = item.strength ? ` ${item.strength}` : "";
  const form = item.form ? `${item.form} ` : "";
  if (s.genericDisplay === "generic" && generic) {
    return `${esc(form)}<b>${esc(s.drugNameCase === "upper" ? generic.toUpperCase() : generic)}</b>${esc(strength)}`;
  }
  const gen = s.genericDisplay === "brand_generic" && generic ? ` <span class="gen">(${esc(generic)})</span>` : "";
  return `${esc(form)}<b>${esc(brand)}</b>${esc(strength)}${gen}`;
}

function ageText(p: PatientInfo, n: Numerals): string {
  const parts: string[] = [];
  if (p.ageYears) parts.push(`${digits(p.ageYears, n)} Y`);
  if (p.ageMonths) parts.push(`${digits(p.ageMonths, n)} M`);
  if (p.ageDays) parts.push(`${digits(p.ageDays, n)} D`);
  return parts.join(" ");
}

function section(title: string, body: string): string {
  return body ? `<section><h3>${esc(title)}</h3>${body}</section>` : "";
}

function list(items: string[]): string {
  const clean = items.map((s) => s.trim()).filter(Boolean);
  return clean.length ? `<ul>${clean.map((i) => `<li>${esc(i)}</li>`).join("")}</ul>` : "";
}

/** Items on one line, comma separated ("Fever × 3 days, Cough, Hearing loss (R)"); wraps only when it must. */
function inline(items: string[]): string {
  const clean = items.map((s) => s.trim()).filter(Boolean);
  return clean.length ? `<p class="inline">${clean.map(esc).join(", ")}</p>` : "";
}

/** History as editable lines: the legacy free-text history first (one line per line of text), then the picked lines. */
export function historyLines(doc: Pick<PrescriptionDoc, "history" | "histories">): string[] {
  return [...(doc.history ?? "").split("\n"), ...(doc.histories ?? [])].map((s) => s.trim()).filter(Boolean);
}

/** The O/E values, printed in the patient strip after the ID: the vitals, then the doctor's own "label: value" rows. */
function oeValues(doc: PrescriptionDoc): { label: string; value: string }[] {
  const v = doc.vitals;
  const rows: { label: string; value: string }[] = [];
  if (v.bpSystolic && v.bpDiastolic) rows.push({ label: "BP", value: `${v.bpSystolic}/${v.bpDiastolic} mmHg` });
  if (v.pulse) rows.push({ label: "Pulse", value: `${v.pulse} b/m` });
  if (v.tempF) rows.push({ label: "Temp", value: `${v.tempF} °F` });
  if (v.spo2) rows.push({ label: "SpO₂", value: `${v.spo2}%` });
  if (v.respRate) rows.push({ label: "RR", value: `${v.respRate}/min` });
  if (v.weightKg) rows.push({ label: "Wt", value: `${v.weightKg} kg` });
  if (v.heightCm) rows.push({ label: "Ht", value: `${v.heightCm} cm` });
  const b = bmi(v.weightKg, v.heightCm);
  if (b) rows.push({ label: "BMI", value: String(b) });
  for (const l of doc.oeFindings ?? []) if (l.label.trim() && l.value.trim()) rows.push({ label: l.label.trim(), value: l.value.trim() });
  return rows;
}

/** The free-text examination under its heading ("<b>O/E:</b> Throat congested"); the O/E values print with the patient. */
function oeBlock(doc: PrescriptionDoc, title: string): string {
  const exam = doc.examination?.trim();
  if (!exam) return "";
  return `<section><p class="pre"><b>${esc(title.trim().replace(/:$/, ""))}:</b> ${esc(exam)}</p></section>`;
}

/** "১ মাস পর আসবেন। (তারিখঃ ১১-০৭-২০২৬)": the relative period plus the date it falls on. */
function followUpText(doc: PrescriptionDoc, date: string, s: PrintSettings): string {
  const f = doc.followUp;
  const due = followUpDate(f, date);
  if (!f || f.kind === "none" || !due) return "";
  const when = formatDateDmy(due, s.numerals);
  if (f.kind === "date") return s.instructionLang === "bn" ? `${when} তারিখে আসবেন।` : `Come on ${when}.`;
  const d = formatDuration({ kind: "fixed", value: f.value, unit: f.unit }, s.instructionLang, s.numerals);
  return s.instructionLang === "bn" ? `${d} পর আসবেন। (তারিখঃ ${when})` : `Come after ${d} (on ${when}).`;
}

/** "Birth wt: 1.7 kg", "Born at 30 weeks" for children under 2. */
function birthNotes(p: PatientInfo): string[] {
  if (p.ageYears && p.ageYears >= 2) return [];
  return [
    p.birthWeightKg ? `Birth wt: ${p.birthWeightKg} kg` : "",
    p.gestationalAgeWeeks ? `Born at ${p.gestationalAgeWeeks} weeks${p.gestationalAgeWeeks < 37 ? " (preterm)" : ""}` : "",
  ].filter(Boolean);
}

/** Lines the doctor typed, without a blank line at either end. */
function keptLines(s: string | undefined | null): string[] {
  const t = (s ?? "").replace(/\r\n/g, "\n").trim();
  return t ? t.split("\n") : [];
}

/** Where the chamber is: name (bold), room number and address, as HTML lines. */
function chamberIdentity(c: ChamberHeader, lang: Lang): string {
  const nameLines = keptLines(c.name);
  const addressLines = keptLines(c.address);
  if (!nameLines.length && !addressLines.length) return "";
  const room = c.room?.trim();
  const lines = [room ? `${lang === "bn" ? "রুম নং" : "Room No"}: ${room}` : "", ...addressLines].filter(Boolean);
  const name = nameLines.map((l) => `<b>${esc(l)}</b>`).join("<br>");
  return `${name}${lines.map((l) => `<br>${esc(l)}`).join("")}`;
}

/** When and how to reach the doctor there: schedule (or free-text hours), serial and chamber phone, as each is enabled. */
function chamberContactLines(c: ChamberHeader, s: PrintSettings, lang: Lang): string[] {
  const slots = s.showSchedule ? (c.schedule ?? []).map((sl) => formatSlot(sl, lang, s.numerals)).filter(Boolean) : [];
  return [
    ...(slots.length ? slots : s.showSchedule && c.hours ? [c.hours] : []),
    s.showSerialPhone && c.serialPhone ? `${lang === "bn" ? "সিরিয়াল" : "Serial"}: ${c.serialPhone}` : "",
    s.showChamberPhone ? (c.phone ?? "") : "",
  ].filter(Boolean);
}

/** One chamber's identity and contact lines in a single block (the header chamber list). */
function chamberBlock(c: ChamberHeader, s: PrintSettings, lang: Lang): string {
  const identity = chamberIdentity(c, lang);
  if (!identity) return "";
  return `<div class="chamber">${identity}${chamberContactLines(c, s, lang).map((l) => `<br>${esc(l)}`).join("")}</div>`;
}

/** Bangla rendering of a BMDC number: "A-39542" → "এ-৩৯৫৪২". */
function bmdcBn(n: string): string {
  return toBnDigits(n.replace(/^A(?=[-\s\d])/i, "এ").replace(/^D(?=[-\s\d])/i, "ডি"));
}

const COURSE_LINE = { bn: "সম্পূর্ণ কোর্স শেষ করুন", en: "Complete the full course" };

/** Render a self-contained, printable HTML document for a prescription. */
export function renderPrescriptionHtml(input: RenderInput): string {
  const { doc, patient, doctor, chamber, settings: s } = input;
  const { widthMm, heightMm } = paperDimensions(s.paper);
  const pad = s.mode === "pad";
  const lang = s.instructionLang;
  const hidden = new Set(s.hiddenSections ?? []);
  const sec = (key: SectionKey, body: string) =>
    hidden.has(key) ? "" : section(s.sectionLabels?.[key]?.trim() || defaultSectionLabel(key, lang), body);

  const logo = safeImageDataUrl(chamber.logoDataUrl);
  const header = pad
    ? ""
    : `<header>
        <div class="doc">
          <div class="dname">${esc(doctor.nameEn)}</div>
          <div>${esc(doctor.degreesEn.join(", "))}</div>
          ${doctor.designation ? `<div>${esc(doctor.designation)}</div>` : ""}
          ${doctor.institution ? `<div>${esc(doctor.institution)}</div>` : ""}
          <div class="bmdc">BMDC Reg. No: ${esc(doctor.bmdcNumber)}</div>
        </div>
        ${logo ? `<div class="logo"><img src="${esc(logo)}" alt=""></div>` : ""}
        ${
          doctor.nameBn
            ? `<div class="doc bn-right">
                <div class="dname">${esc(doctor.nameBn)}</div>
                <div>${esc((doctor.degreesBn ?? []).join(", "))}</div>
                ${doctor.specialty ? `<div>${esc(doctor.specialty)}</div>` : ""}
                ${doctor.bmdcNumber ? `<div class="bmdc-bn">বিএমডিসি রেজি. নং: ${esc(bmdcBn(doctor.bmdcNumber))}</div>` : ""}
              </div>`
            : ""
        }
      </header>${
        s.chambersInHeader && input.chambers?.length
          ? `<div class="chambers">${input.chambers.map((c) => chamberBlock(c, s, lang)).join("")}</div>`
          : ""
      }`;

  const patientStrip = `<div class="patient">
      <span><b>Name:</b> ${esc(patient.name)}</span>
      <span><b>Age:</b> ${esc(ageText(patient, "en"))}</span>
      <span><b>Sex:</b> ${esc(patient.sex ? patient.sex[0]!.toUpperCase() : "")}</span>
      ${patient.address ? `<span><b>Address:</b> ${esc(patient.address)}</span>` : ""}
      <span><b>Date:</b> ${esc(formatDateDmy(input.date, "en", "/"))}</span>
      ${doc.visitNo ? `<span class="visit-no"><b>Visit No:</b> ${doc.visitNo}</span>` : ""}
      ${patient.patientCode ? `<span><b>ID:</b> ${esc(patient.patientCode)}</span>` : ""}
      ${hidden.has("oe") ? "" : oeValues(doc).map((o) => `<span class="oe"><b>${esc(o.label)}:</b> ${esc(o.value)}</span>`).join("\n      ")}
    </div>`;

  // Older prescriptions have no `kind`; their drums are titled "Right TM" / "Left TM".
  const hasTm = (doc.diagrams ?? []).some((d) => d.kind === "tm" || /^(Right|Left) TM$/.test(d.title));
  const blankTm = s.tmMapAlways && !hasTm
    ? [{ title: "Right TM", svg: eardrumSvg(undefined, "right"), kind: "tm" as const, section: "ear" }, { title: "Left TM", svg: eardrumSvg(undefined, "left"), kind: "tm" as const, section: "ear" }]
    : [];
  const blankSketches = (Array.isArray(s.sketchesAlways) ? s.sketchesAlways : [])
    .filter((id) => isSketchId(id) && !(doc.diagrams ?? []).some((d) => d.kind === "sketch" && d.ref === id))
    .map((id) => ({ title: SKETCHES[id].title, svg: sketchSvg(id), kind: "sketch" as const, ref: id, section: SKETCHES[id].section }));
  const allDiagrams = [...blankTm, ...(doc.diagrams ?? []), ...blankSketches];
  const isTm = (d: (typeof allDiagrams)[number] | undefined) => !!d && (d.kind === "tm" || /^(Right|Left) TM$/.test(d.title));
  // Diagrams come from the client-writable prescription doc: sanitise before embedding.
  // A picture's caption goes under it; a key's heading ("Key") goes above its rows. A drum has none: it is marked R / L
  // inside its own picture, so "Right TM" / "Left TM" would only repeat that.
  const figure = (d: (typeof allDiagrams)[number], style = "") => {
    const legend = d.kind === "tm-legend" || d.kind === "legend";
    const svg = `<div class="svg">${sanitizeSvg(d.svg)}</div>`, caption = isTm(d) ? "" : `<figcaption>${esc(d.title)}</figcaption>`;
    return `<figure class="diagram${legend ? " legend" : ""}${isTm(d) ? " tm" : ""}${d.kind === "sketch" && d.ref === "neck" ? " neck" : ""}"${style}>${legend ? caption + svg : svg + caption}</figure>`;
  };
  const figures = (ds: typeof allDiagrams) => {
    const out: string[] = [];
    for (let i = 0; i < ds.length; i++) {
      const d = ds[i]!, key = ds[i + 2];
      // Both drums and their key on one row: the drums shrink so the key fits beside the left one, its text kept at
      // one size (width from its viewBox, clamped since the svg is client-writable).
      if (isTm(d) && isTm(ds[i + 1]) && key?.kind === "tm-legend") {
        const w = Math.min(120, Math.max(20, Number(/viewBox="0 0 ([\d.]+)/.exec(key.svg)?.[1]) || 86));
        out.push(`<div class="ear-row">${figure(d)}${figure(ds[i + 1]!)}${figure(key, ` style="width:${(w * 0.31).toFixed(1)}mm"`)}</div>`);
        i += 2;
      } else out.push(figure(d));
    }
    return out.join("");
  };

  // Each picture prints under its own exam section; the rest (older prescriptions, or a blank
  // "always print" picture whose section has no findings) print together after all findings.
  const groups = doc.specialtyFindings ?? [];
  const tmPrinted = allDiagrams.some(isTm);
  const placed = (d: (typeof allDiagrams)[number]) => typeof d.section === "string" && groups.some((g) => g.id === d.section);
  const groupBody = (g: (typeof groups)[number]) => {
    const own = g.id ? allDiagrams.filter((d) => d.section === g.id) : [];
    const pics = figures(own);
    // The drums show the TM map, so its words ("R: central perforation (large) · L: …") don't print when they do.
    // Exams saved before the abovePictures flag existed are matched by their "TM map" label.
    const tmWords = (l: ExamFindingLine) => l.abovePictures || l.label === "TM map";
    const shown = tmPrinted ? g.lines.filter((l) => !tmWords(l)) : g.lines;
    const lines = shown.length ? `<ul>${shown.map((l) => `<li><b>${esc(l.label)}:</b> ${esc(l.value)}</li>`).join("")}</ul>` : "";
    return lines + (pics ? `<div class="diagrams">${pics}</div>` : "");
  };
  // A section placed under Investigations (audiology results) prints inside Ix, after the advised tests, without its
  // own heading. If the doctor hides Ix, it keeps its heading with the examination, so the results still print.
  const underIx = (g: (typeof groups)[number]) => g.placement === "ix" && !hidden.has("ix");
  const specialty = groups
    .filter((g) => !underIx(g))
    .map((g) => section(g.title, groupBody(g)))
    .join("");
  const ixResults = groups.filter(underIx).map(groupBody).join("");
  const diagrams = figures(allDiagrams.filter((d) => !placed(d)));

  // Letterhead: centred in the footer. Pad: the pad prints its own footer, so the QR stays in the body.
  const qr = s.showQr && input.qrSvg ? `<div class="qr">${sanitizeSvg(input.qrSvg)}</div>` : "";
  const barcodeSvg = s.showBarcode && patient.patientCode ? code39Svg(patient.patientCode) : null;
  const left = [
    barcodeSvg ? `<div class="barcode">${barcodeSvg}<div>*${esc(patient.patientCode!.toUpperCase())}*</div></div>` : "",
    sec("cc", inline(doc.chiefComplaints)),
    sec("history", (doc.history?.trim() ? `<p class="pre">${esc(doc.history.trim())}</p>` : "") + list(doc.histories ?? [])),
    hidden.has("oe") ? "" : oeBlock(doc, s.sectionLabels?.oe?.trim() || defaultSectionLabel("oe", lang)),
    specialty,
    diagrams ? `<section class="diagrams">${diagrams}</section>` : "",
    sec("labs", list((doc.labFindings ?? []).map((l) => l.text))),
    sec("ix", list(doc.investigations) + ixResults),
    sec("dx", list(doc.diagnoses)),
    sec("plan", list(doc.plan ?? [])),
    sec("notes", list([...birthNotes(patient), ...(doc.notes ?? [])])),
  ].join("");
  // Pad: the QR is pinned to the bottom of the left column, so nothing sits under the body to cut the divider short.
  const leftQr = pad ? qr : "";

  const items = doc.items
    .map((it, i) => {
      const { main, duration } = formatInstructionParts(it, lang, s.numerals);
      return `<li class="rx-item">
        <div class="lines">
          <div class="drug"><span class="num">${digits(i + 1, s.numerals)}.</span> ${drugName(it, s)}</div>
          ${main ? `<div class="instr">${esc(main)}</div>` : ""}
          ${it.note ? `<div class="note">${esc(it.note)}</div>` : ""}
          ${it.isAntibiotic ? `<div class="note course">${COURSE_LINE[lang]}</div>` : ""}
        </div>
        <div class="dur">${duration ? `- ${esc(duration)}` : ""}</div>
      </li>`;
    })
    .join("");

  const fu = followUpText(doc, input.date, s);
  const sig = safeImageDataUrl(input.signatureDataUrl);
  const right = [
    `<div class="rx-symbol">℞</div>`,
    items ? `<ol class="rx">${items}</ol>` : "",
    doc.rxNote?.trim() ? `<div class="rx-note pre">${esc(doc.rxNote.trim())}</div>` : "",
    sec("advice", list(doc.advice)),
    fu ? sec("followUp", `<p>${esc(fu)}</p>`) : "",
    // The signature closes the prescription, right after its last line.
    `<div class="sign">${sig ? `<img src="${esc(sig)}" alt="">` : ""}<div class="line">Signature</div></div>`,
    input.footerNote ? `<div class="footnote">${esc(input.footerNote)}</div>` : "",
  ].join("");

  // Footer: where the chamber is on the left, QR in the middle, when/how to reach the doctor on the right.
  const footerText = chamber.footerText?.trim();
  const listedInHeader = s.chambersInHeader && !!input.chambers?.length;
  const footLeft = listedInHeader ? "" : chamberIdentity(chamber, lang);
  const footRight = listedInHeader ? "" : chamberContactLines(chamber, s, lang).map(esc).join("<br>");
  const footer =
    pad || (!footLeft && !qr && !footRight && !footerText)
      ? ""
      : `<footer>${
          footLeft || qr || footRight
            ? `<div class="foot"><div class="foot-left">${footLeft}</div><div class="foot-qr">${qr}</div><div class="foot-right">${footRight}</div></div>`
            : ""
        }${footerText ? `<div class="policy">${esc(footerText)}</div>` : ""}</footer>`;

  const m = pageMargins(s);
  // 2+ pages: "Page 1 of 2" in a strip at the bottom of every page, and the page box as tall as all the pages, so the
  // footer lands at the bottom of the last one. The strip comes out of the bottom margin (at least PAGE_NO_MM).
  const pages = Math.min(50, Math.max(1, Math.floor(Number(input.pages) || 1)));
  const numbered = pages > 1;
  const pageBoxMm = r1(pages * pageContentHeightMm(s, numbered));
  const pageRule = numbered
    ? `@page { size: ${widthMm}mm ${heightMm}mm; margin: 0 0 ${PAGE_NO_MM}mm 0;
  @bottom-right { content: "Page " counter(page) " of " counter(pages); font-family: "RxLatin", sans-serif; font-size: 8pt; padding-right: ${m.right}mm; } }`
    : `@page { size: ${widthMm}mm ${heightMm}mm; margin: 0; }`;
  const sheetBottomMm = numbered ? r1(Math.max(0, m.bottom - PAGE_NO_MM)) : m.bottom;

  return `<!doctype html>
<html lang="bn">
<head>
<meta charset="utf-8">
<title>${esc(prescriptionFileName({ name: patient.name, mobile: patient.mobile, id: patient.patientCode, date: input.date }).replace(/\.pdf$/, ""))}</title>
<style>
@font-face { font-family: "RxBengali"; src: url("${input.fonts.bengali}") format("truetype"); font-weight: 100 900; }
@font-face { font-family: "RxLatin"; src: url("${input.fonts.latin}") format("truetype"); font-weight: 100 900; }
/* A zero page margin leaves the browser no room for its own header/footer (date, title, URL, page number).
   The sheet's padding carries the margins instead: the pad's pre-printed header/footer space and the printer
   offset. It is cloned onto every page, so it repeats when a long prescription flows onto page 2. */
${pageRule}
* { box-sizing: border-box; }
html, body { margin: 0; padding: 0; background: #fff; color: #000; }
.sheet { padding: ${m.top}mm ${m.right}mm ${sheetBottomMm}mm ${m.left}mm; -webkit-box-decoration-break: clone; box-decoration-break: clone; }
body { font-family: "RxLatin", "RxBengali", sans-serif; font-size: ${s.fontSizePt}pt; line-height: 1.35; }
.page { min-height: ${pageBoxMm}mm; display: flex; flex-direction: column; }
header { display: flex; justify-content: space-between; border-bottom: 1.5pt solid #000; padding-bottom: 2mm; }
header .dname { font-size: 1.35em; font-weight: 700; }
header .bn-right { text-align: right; }
header .bmdc, header .bmdc-bn { font-weight: 600; }
.patient { display: flex; flex-wrap: wrap; gap: 1mm 6mm; padding: 2mm 0; border-bottom: 0.75pt solid #000; }
.body { flex: 1; display: grid; grid-template-columns: ${s.leftColumnPct}% 1fr; }
/* A two-row grid, not a column flexbox: the findings fill the column and the pad's QR takes the bottom row. Chrome
   moves a flexbox column that runs past page 1 wholly onto page 2, which printed page 1 blank. */
.left { border-right: 0.75pt solid #000; padding: 2mm 3mm 2mm 0; display: grid; grid-template-rows: 1fr auto; }
.right { padding: 2mm 0 2mm 4mm; }
/* A section may run onto the next page; only its pieces stay whole. A section kept whole that is too tall for the
   rest of the page moves to the next one, and at the top of a column it takes the whole column with it, leaving
   page 1 blank. A heading stays with its first line. */
section { margin-bottom: 2.5mm; }
h3 { font-size: 0.95em; margin: 0 0 1mm; text-decoration: underline; break-after: avoid; }
li, .oe, .pre { break-inside: avoid; }
ul { margin: 0; padding-left: 4mm; }
.pre { white-space: pre-wrap; margin: 0; }
.inline { margin: 0; }
.rx-symbol { font-size: 2em; font-weight: 700; line-height: 1; margin-bottom: 1mm; }
ol.rx { list-style: none; padding: 0; margin: 0 0 3mm; }
.rx-item { margin-bottom: 2.5mm; break-inside: avoid; display: grid; grid-template-columns: 1fr auto; column-gap: 4mm; }
.rx-item .dur { align-self: center; white-space: nowrap; }
.patient .oe { white-space: nowrap; }
.rx-note { margin: 0 0 3mm; }
.rx-item .num { display: inline-block; min-width: 5mm; }
.rx-item .gen { font-size: 0.85em; }
.rx-item .instr, .rx-item .note { padding-left: 5mm; }
.rx-item .note { font-size: 0.9em; }
ul + .diagrams { margin-top: 1.5mm; }
.diagram { display: inline-block; margin: 0 2mm 2mm 0; text-align: center; font-size: 0.8em; }
.diagram .svg svg { width: 28mm; height: auto; }
.diagram.legend { vertical-align: top; text-align: left; }
.diagram.legend figcaption { margin-bottom: 0.5mm; }
.diagram.legend .svg svg { width: 32mm; }
.ear-row { display: flex; align-items: flex-start; gap: 2mm; margin-bottom: 2mm; break-inside: avoid; }
.ear-row .diagram { margin: 0; }
.ear-row .diagram.tm { flex: 0 1 20mm; min-width: 14mm; }
.ear-row .diagram.tm .svg svg, .ear-row .diagram.legend .svg svg { width: 100%; }
.ear-row .diagram.legend { flex: 0 0 auto; }
.diagram.neck .svg svg { width: 30mm; }
.qr { padding-top: 2mm; break-inside: avoid; }
.qr svg { width: 18mm; height: 18mm; }
.sign { text-align: center; min-width: 45mm; width: fit-content; margin: calc(15mm + 40px) 0 0 auto; break-inside: avoid; }
.sign img { max-height: 14mm; max-width: 45mm; }
.sign .line { border-top: 0.75pt solid #000; padding-top: 1mm; }
footer { border-top: 1.5pt solid #000; padding-top: 2mm; font-size: 0.9em; break-inside: avoid; }
footer .policy { text-align: center; margin-top: 1mm; }
.foot { display: grid; grid-template-columns: 1fr auto 1fr; gap: 4mm; align-items: start; }
.foot-right { text-align: right; }
footer .qr { margin: 0; padding: 0; }
header .logo { display: flex; align-items: center; }
header .logo img { max-height: 18mm; max-width: 30mm; }
.chambers { display: grid; grid-template-columns: repeat(auto-fit, minmax(50mm, 1fr)); gap: 2mm 4mm; padding: 1.5mm 0; border-bottom: 0.75pt solid #000; font-size: 0.85em; }
.barcode { margin-bottom: 2mm; text-align: center; font-size: 0.8em; letter-spacing: 0.5pt; }
.barcode svg { display: block; margin: 0 auto 0.5mm; }
.footnote { font-size: 0.75em; text-align: center; color: #333; margin-top: 2mm; }
@media screen {
  body { background: #e5e7eb; }
  .sheet { width: ${widthMm}mm; min-height: ${heightMm}mm; margin: 8mm auto; background: #fff; box-shadow: 0 1px 6px rgba(0,0,0,.2); }
}
</style>
</head>
<body>
<div class="sheet">
<div class="page">
  ${header}
  ${patientStrip}
  <div class="body">
    <div class="left"><div class="left-main">${left}</div>${leftQr}</div>
    <div class="right">${right}</div>
  </div>
  ${footer}
</div>
</div>
</body>
</html>`;
}

/** Effective @page margins: user margins + pad reserved space + printer offset (never negative). */
export function pageMargins(s: PrintSettings): { top: number; right: number; bottom: number; left: number } {
  const pad = s.mode === "pad";
  const clamp = (n: number) => Math.max(0, Math.round(n * 10) / 10);
  return {
    top: clamp(s.marginTopMm + (pad ? s.padHeaderMm : 0) + s.offsetYmm),
    bottom: clamp(s.marginBottomMm + (pad ? s.padFooterMm : 0) - s.offsetYmm),
    left: clamp(s.marginLeftMm + s.offsetXmm),
    right: clamp(s.marginRightMm - s.offsetXmm),
  };
}
